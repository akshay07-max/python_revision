# 1] int, float, complex = immutable 
# eg 5, 5.5, 2+4j

a = 10 
print(a)
print(type(a))

b = 2.32
print(b)
print(type(b))


c = 33+33j
print(c)
print(type(c))

# 2] str = immutable. eg. "Hello"
d = "Good Boy"
print(d)
print(type(d))

# 3] bool = Immutable. eg. True, False
f = True
print(f)
print(type(f))


# 4] list = Mutable eg. [1,2,3,4]
g = [12, 32, 34, 55]
print(g)
print(type(g))

# 5] Tuple = Immutable eg. (12, 44, 45)
h = (12, 42, 55)
print(h)
print(type(h))

# 6] set = Mutable eg. {1,2,4,5}
i = {1, 3, 5, 7}
print(i)
print(type(i))
